/**
 * Represents a date and time object.
 */
export interface IGenshinDateTime {
  /**
   * The year.
   */
  year: number
  /**
   * The month.
   */
  month: number
  /**
   * The day.
   */
  day: number
  /**
   * The hour.
   */
  hour: number
  /**
   * The minute.
   */
  minute: number
  /**
   * The second.
   */
  second: number
}
